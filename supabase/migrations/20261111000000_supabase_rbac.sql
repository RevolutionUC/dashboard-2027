-- Supabase RBAC (https://supabase.com/docs/guides/database/postgres/custom-claims-and-role-based-access-control-rbac)
--
-- Roles live in public.user_roles. A Custom Access Token Hook copies each user's role into
-- their JWT as the `user_role` claim; the app authorizes from that signed claim.
-- No row in user_roles = not approved.
--
-- After applying, enable the hook in the Supabase dashboard:
--   Authentication -> Hooks -> Customize Access Token (JWT) Claims -> public.custom_access_token_hook

CREATE TYPE "public"."app_role" AS ENUM ('admin', 'lead', 'organizer');

CREATE TABLE "public"."user_roles" (
  "id" bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "user_id" uuid NOT NULL UNIQUE REFERENCES auth.users (id) ON DELETE CASCADE,
  "role" "public"."app_role" NOT NULL,
  "created_at" timestamptz NOT NULL DEFAULT now(),
  "updated_at" timestamptz NOT NULL DEFAULT now()
);

COMMENT ON TABLE "public"."user_roles" IS 'Dashboard role per Supabase auth user. Exposed in the JWT as the user_role claim.';

ALTER TABLE "public"."user_roles" ENABLE ROW LEVEL SECURITY;

-- The auth server runs the hook as supabase_auth_admin and needs to read roles.
GRANT ALL ON TABLE "public"."user_roles" TO supabase_auth_admin;
REVOKE ALL ON TABLE "public"."user_roles" FROM authenticated, anon, public;

CREATE POLICY "Allow auth admin to read user roles"
  ON "public"."user_roles"
  AS PERMISSIVE FOR SELECT
  TO supabase_auth_admin
  USING (true);

CREATE OR REPLACE FUNCTION "public"."custom_access_token_hook"(event jsonb)
RETURNS jsonb
LANGUAGE plpgsql
STABLE
AS $$
DECLARE
  claims jsonb;
  assigned_role public.app_role;
BEGIN
  SELECT role INTO assigned_role
  FROM public.user_roles
  WHERE user_id = (event ->> 'user_id')::uuid;

  claims := event -> 'claims';

  IF assigned_role IS NOT NULL THEN
    claims := jsonb_set(claims, '{user_role}', to_jsonb(assigned_role));
  ELSE
    claims := jsonb_set(claims, '{user_role}', 'null');
  END IF;

  RETURN jsonb_set(event, '{claims}', claims);
END;
$$;

GRANT USAGE ON SCHEMA public TO supabase_auth_admin;
GRANT EXECUTE ON FUNCTION "public"."custom_access_token_hook" TO supabase_auth_admin;
REVOKE EXECUTE ON FUNCTION "public"."custom_access_token_hook" FROM authenticated, anon, public;

-- Carry over roles of users who were already approved (or admins) and aren't banned.
INSERT INTO "public"."user_roles" ("user_id", "role")
SELECT
  au.id,
  (CASE WHEN u.role = 'admin' OR u.dashboard_role = 'admin' THEN 'admin' ELSE u.dashboard_role END)::public.app_role
FROM "public"."user" u
JOIN auth.users au ON au.id::text = u.id
WHERE COALESCE(u.banned, false) = false
  AND (
    u.role = 'admin'
    OR u.dashboard_role = 'admin'
    OR (
      u.dashboard_role IN ('lead', 'organizer')
      AND EXISTS (
        SELECT 1 FROM "public"."access_requests" ar
        WHERE ar.user_id = u.id AND ar.status = 'approved'
      )
    )
  )
ON CONFLICT ("user_id") DO NOTHING;

-- Roles are no longer stored on the app user row.
ALTER TABLE "public"."user" DROP COLUMN "role";
ALTER TABLE "public"."user" DROP COLUMN "dashboard_role";
